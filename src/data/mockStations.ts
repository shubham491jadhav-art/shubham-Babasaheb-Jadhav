const generateSlots = (baseOffset: number = 0): TimeSlot[] => {
  const times = [
    { start: '10:00', end: '10:45', peak: 1.0 },
    { start: '10:45', end: '11:30', peak: 1.0 },
    { start: '11:30', end: '12:15', peak: 1.15 },
    { start: '12:15', end: '13:00', peak: 1.15 },
    { start: '13:00', end: '13:45', peak: 1.0 },
    { start: '13:45', end: '14:30', peak: 1.0 },
    { start: '14:30', end: '15:15', peak: 1.0 },
    { start: '15:15', end: '16:00', peak: 1.1 },
    { start: '16:00', end: '16:45', peak: 1.2 },
    { start: '16:45', end: '17:30', peak: 1.25 },
    { start: '17:30', end: '18:15', peak: 1.25 },
    { start: '18:15', end: '19:00', peak: 1.15 },
    { start: '19:00', end: '19:45', peak: 1.0 },
    { start: '20:00', end: '20:45', peak: 0.9 },
  ];

  return times.map((t, idx) => ({
    id: `slot-${idx + 1}-${baseOffset}`,
    startTime: t.start,
    endTime: t.end,
    // First 2 slots may be occupied based on baseOffset
    isAvailable: !((idx + baseOffset) % 4 === 1),
    priceModifier: t.peak,
  }));
};

